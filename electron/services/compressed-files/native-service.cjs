const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const engine = require('./engine.cjs');
const { createArchiveService } = require('./operations.cjs');

// Native tools reuse the scoped file/output transaction implementation. This
// descriptor is internal and is never installed, enumerated, or executed as a plugin.
const descriptor = Object.freeze({ componentId: 'builtin-compression', componentVersion: '1', service: {
  capabilities: ['project.files.page', 'project.files.inputToken', 'project.input.tokens', 'project.media.page', 'project.output', 'project.files.mutate', 'component.storage', 'tasks', 'component.settings'],
  permissions: ['project.files.read', 'project.input.read', 'project.media.read', 'project.output.write', 'project.files.write', 'component.storage', 'tasks', 'component.settings'],
} });
const methods = { run: 'compression.run.v1', current: 'compression.current.v1', cancel: 'compression.cancel.v1', publish: 'compression.publish.v1', preferences: 'compression.preferences.v1' };
const createCompressedFilesService = ({ broker, resolveContext, mediaAccessService, shell, executable = engine.enginePath }) => {
  const requests = new Map(), sessions = new Map(), opening = new Map(), closedOwners = new Set(), pending = new Set();
  let destroyed = false;
  const operations = createArchiveService((id, method, payload) => broker.invoke(descriptor, method, payload, requests.get(id)), { executable });
  const frameFor = async (owner, request) => {
    const input = request.context || {};
    const context = await resolveContext(input);
    const paths = request.payload?.relativePaths || (request.relativePath ? [request.relativePath] : []);
    const directories = paths.map(value => engine.safeRelative(value).split('/').slice(0, -1));
    const common = [...(directories[0] || [])];
    for (const directory of directories.slice(1)) while (common.length && common.some((part, index) => part.toLowerCase() !== directory[index]?.toLowerCase())) common.pop();
    const pageId = String(input.sourcePageId || 'files').slice(0, 160);
    return { id: crypto.randomUUID(), method: methods[request.action], payload: request.payload || {}, context: {
      ...context, componentId: descriptor.componentId, componentVersion: '1', surface: 'component.sidePanel',
      instanceId: `native-compression:${owner}:${pageId}`, sourcePageId: pageId, contributionId: 'tool',
      scopeRelativePath: paths.length ? common.join('/') : '', selectedRelativePaths: paths,
    } };
  };
  const withFrame = async (frame, run) => {
    requests.set(frame.id, frame.context);
    try { return await run(frame); } finally { requests.delete(frame.id); }
  };
  const requireSession = (owner, id) => {
    const session = sessions.get(id);
    if (!session || session.owner !== owner || session.closed) throw new Error('压缩包已关闭，请重新打开');
    return session;
  };
  const materialize = (session, entry, secret = '') => {
    const run = async () => {
      engine.checkCancelled(session.controller.signal);
      let target = session.members.get(entry.relativePath);
      if (!target) {
        const password = secret || session.password;
        if (typeof password !== 'string' || password.length > 256 || /[\x00-\x1f]/.test(password)) throw new Error('密码无效');
        const destination = path.join(session.work, `member-${crypto.randomUUID()}`);
        try { target = await engine.extractMember({ executable: typeof executable === 'function' ? executable() : executable, archive: session.privateArchive, destination, entry, password, signal: session.controller.signal }); }
        catch (error) {
          if (path.dirname(destination) === session.work && /^member-[a-f0-9-]{36}$/.test(path.basename(destination))) await fs.promises.rm(destination, { recursive: true, force: true });
          throw error;
        }
        session.password = password; session.members.set(entry.relativePath, target);
      }
      engine.checkCancelled(session.controller.signal);
      return target;
    };
    session.tail = session.tail.catch(() => undefined).then(run);
    return session.tail;
  };
  const close = async session => {
    if (session.closed) return;
    session.closed = true; sessions.delete(session.id); session.controller.abort();
    await session.tail.catch(() => undefined);
    session.password = '';
    for (const token of session.tokens) await mediaAccessService.revokeToken(token);
    // work is generated by prepareSession, never accepted from IPC.
    if (/^inspect-[a-f0-9-]{36}$/.test(path.basename(session.work))) await fs.promises.rm(session.work, { recursive: true, force: true });
  };
  const handle = async (owner, input) => {
    if (destroyed || closedOwners.has(owner)) throw new Error('压缩文件浏览已结束');
    if (!input || typeof input !== 'object' || Array.isArray(input)) throw new Error('无效的压缩请求');
    if (methods[input.action]) return withFrame(await frameFor(owner, input), frame => operations.handle(frame));
    if (input.action === 'open') {
      if (opening.has(owner)) throw new Error('正在打开压缩包，请稍后重试');
      const controller = new AbortController();
      opening.set(owner, controller);
      try {
        if ([...sessions.values()].filter(session => session.owner === owner).length >= 8) throw new Error('请先关闭不再使用的压缩包');
        const frame = await frameFor(owner, input);
        frame.payload = { relativePath: input.relativePath, password: input.password || '' };
        const result = await withFrame(frame, value => operations.prepareSession(value, controller.signal));
        const id = crypto.randomUUID();
        const session = { ...result, id, owner, password: input.password || '', context: frame.context, tail: Promise.resolve(), tokens: [], members: new Map(), controller: new AbortController(), closed: false };
        if (destroyed || closedOwners.has(owner)) { await close(session); throw new Error('压缩文件浏览已结束'); }
        sessions.set(id, session);
        try {
          const encrypted = result.entries.find(entry => entry.encrypted && !entry.directory);
          if (encrypted) {
            if (!session.password) throw Object.assign(new Error('压缩包需要密码'), { code: 'ARCHIVE_PASSWORD_REQUIRED' });
            await materialize(session, encrypted);
          }
          const entries = result.entries.map(entry => {
            if (entry.directory) return entry;
            const token = mediaAccessService.grantDeferredPath(() => materialize(session, entry));
            session.tokens.push(token);
            return { ...entry, inputPath: `media-token:${token}` };
          });
          return { sessionId: id, archiveName: result.archiveName, entries, totalBytes: result.totalBytes };
        } catch (error) { await close(session); throw error; }
      } finally { opening.delete(owner); }
    }
    if (input.action === 'close') { await close(requireSession(owner, input.sessionId)); return { closed: true }; }
    if (input.action === 'member') {
      const session = requireSession(owner, input.sessionId);
      const member = engine.safeRelative(input.relativePath);
      const entry = session.entries.find(item => item.relativePath === member && !item.directory);
      if (!entry) throw new Error('压缩包内没有此文件');
      const target = await materialize(session, entry, input.password);
      const run = async () => {
        engine.checkCancelled(session.controller.signal);
        if (input.openExternal === true) {
          const error = await shell.openPath(target); if (error) throw new Error(error);
          return { opened: true };
        }
        const token = mediaAccessService.grantPath(target); session.tokens.push(token);
        const extension = path.extname(member).toLowerCase();
        let text;
        if (/^\.(txt|md|json|csv|log|xml|yaml|yml|ini|srt|vtt|css|js|ts|html)$/.test(extension) && entry.size <= 1024 ** 2) text = await fs.promises.readFile(target, 'utf8');
        return { mediaUrl: `photoflow-media://file/${token}`, extension, ...(text === undefined ? {} : { text }) };
      };
      // Keep external opens and media grants inside the session lifetime.
      session.tail = session.tail.catch(() => undefined).then(run);
      return session.tail;
    }
    throw new Error('不支持的压缩操作');
  };
  const request = (owner, input) => {
    const result = handle(owner, input); pending.add(result);
    void result.finally(() => pending.delete(result)).catch(() => undefined);
    return result;
  };
  const closeOwner = owner => { closedOwners.add(owner); opening.get(owner)?.abort(); return Promise.allSettled([...sessions.values()].filter(session => session.owner === owner).map(close)); };
  const destroy = async () => {
    destroyed = true;
    for (const controller of opening.values()) controller.abort();
    for (const job of operations.jobs.values()) job.controller?.abort();
    await Promise.allSettled([...sessions.values()].map(close));
    await Promise.allSettled([...pending]);
  };
  return { request, closeOwner, destroy };
};
module.exports = { createCompressedFilesService };
