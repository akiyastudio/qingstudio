const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const registry = require('../electron/locales/registry.json');
const ids = new Set();
for (const language of registry.languages) {
  if (!/^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/.test(language.id) || ids.has(language.id) || !['ltr', 'rtl'].includes(language.direction)) throw new Error('Invalid language registration');
  ids.add(language.id);
  JSON.parse(fs.readFileSync(path.join(root, 'electron/locales', language.id + '.json'), 'utf8'));
}
if (!ids.has(registry.baseLanguage)) throw new Error('Unregistered base language');
const output = '// Generated by scripts/generate-i18n-catalogs.cjs. Edit the registry and language JSON files.\n'
  + registry.languages.map((language, index) => 'import catalog' + index + ' from ' + JSON.stringify('../../electron/locales/' + language.id + '.json') + ';').join('\n') + '\n'
  + 'export const catalogs = { ' + registry.languages.map((language, index) => JSON.stringify(language.id) + ': catalog' + index).join(', ') + ' };\n'
  + 'export const LANGUAGES = ' + JSON.stringify(registry.languages, null, 2) + ' as const;\n'
  + 'export const BASE_LANGUAGE = ' + JSON.stringify(registry.baseLanguage) + ' as const;\n';
const target = path.join(root, 'src/i18n/catalogs.generated.ts');
if (process.argv.includes('--check')) { if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Regenerate language catalog imports'); }
else fs.writeFileSync(target, output);

const ts = require('typescript');
const parserSource = fs.readFileSync(path.join(root, 'src/i18n/legacy-parser.ts'), 'utf8');
const compiledParser = '// Generated from src/i18n/legacy-parser.ts. Do not edit.\n' + ts.transpileModule(parserSource, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const parserTarget = path.join(root, 'electron/locales/legacy-parser.generated.cjs');
if (process.argv.includes('--check')) { if (!fs.existsSync(parserTarget) || fs.readFileSync(parserTarget, 'utf8') !== compiledParser) throw new Error('Regenerate the shared language parser'); }
else fs.writeFileSync(parserTarget, compiledParser);
